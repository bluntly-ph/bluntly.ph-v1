def _cid(name: str) -> str:
    return f"com_demo_{name[:20]}"


def seed(targets: dict) -> str:
    n_sales = sum(1 + len(t[2]) for t in targets.values())
    total = f"{float(GROSS) * n_sales:.2f}"
    out = [
        "-- Defense demo seed, October 2026 (owner-approved). Generated by docs/release/demo_seed_2026_10.py.",
        "DO $$",
        "BEGIN",
        f"  IF EXISTS (SELECT 1 FROM commissions WHERE csv_source = '{SOURCE}') THEN",
        "    RAISE EXCEPTION 'demo seed already applied';",
        "  END IF;",
        "  IF EXISTS (SELECT 1 FROM marketplace_remittances",
        "             WHERE platform = 'lazada' AND cycle_month = DATE '2026-10-01') THEN",
        "    RAISE EXCEPTION 'a Lazada October remittance already exists';",
        "  END IF;",
    ]
    for name, (uid, review, convert) in targets.items():
        out += [
            f"  -- {name}: one new sale",
            "  INSERT INTO commissions (commission_id, target_type, review_id, reviewer_id, reviewer_share_bps,",
            "    gross_amount, platform_share, reviewer_share, honesty_fund_share, currency, csv_source,",
            "    row_reference, order_status, cycle_month, platform, cleared_at, is_test)",
            f"  VALUES ('{_cid(name)}', 'review', '{review}', '{uid}', 3000,",
            f"    {GROSS}, {PLATFORM}, {REVIEWER}, {FUND}, 'PHP', '{SOURCE}',",
            f"    'DEMO-{name}-sale', 'completed', DATE '2026-10-01', 'lazada', now(), false);",
            f"  UPDATE users SET wallet_balance = wallet_balance + {REVIEWER} WHERE id = '{uid}';",
            "  IF NOT FOUND THEN RAISE EXCEPTION 'reviewer % missing', " f"'{uid}'; END IF;",
        ]
        for cid, (orig_id, _orig_ref) in convert.items():
            out += [
                f"  -- {name}: give QA credit {orig_id} the same split (wallet unchanged: already paid out)",
                "  UPDATE commissions SET is_test = false, reviewer_share_bps = 3000,",
                f"    gross_amount = {GROSS}, platform_share = {PLATFORM}, honesty_fund_share = {FUND},",
                f"    csv_source = '{SOURCE}', row_reference = 'DEMO-{name}-{orig_id}',",
                "    order_status = 'completed', platform = 'lazada', updated_at = now()",
                f"  WHERE id = '{cid}' AND is_test AND reviewer_share = {REVIEWER} AND reviewer_id = '{uid}';",
                "  IF NOT FOUND THEN RAISE EXCEPTION 'QA credit % not in the expected state', " f"'{cid}'; END IF;",
            ]
    out += [
        "  -- Money in: the marketplace's payout for those sales",
        "  INSERT INTO marketplace_remittances (platform, cycle_month, amount_received, received_on, reference)",
        f"  VALUES ('lazada', DATE '2026-10-01', {total}, (now() AT TIME ZONE 'Asia/Manila')::date, '{REMIT_REF}');",
        "  INSERT INTO moderation_logs (log_id, moderator_id, action, notes, context)",
        f"  VALUES ('{LOG_ID}', NULL, 'csv_import', 'DEMO seed: invented sales for the defense (owner-approved)',",
        f"    jsonb_build_object('csv_source', '{SOURCE}', 'imported', {n_sales}, 'gross_each', '{GROSS}',",
        f"      'remittance', '{total}', 'demo', true));",
        "END $$;",
    ]
    return "\n".join(out) + "\n"


def rollback(targets: dict) -> str:
    out = [
        "-- Roll back the October 2026 defense demo seed. Generated by docs/release/demo_seed_2026_10.py.",
        "DO $$",
        "BEGIN",
    ]
    for name, (uid, _review, convert) in targets.items():
        out += [
            f"  UPDATE users SET wallet_balance = wallet_balance - {REVIEWER} WHERE id = '{uid}'",
            f"    AND EXISTS (SELECT 1 FROM commissions WHERE commission_id = '{_cid(name)}');",
            f"  DELETE FROM commissions WHERE commission_id = '{_cid(name)}';",
        ]
        for cid, (_orig_id, orig_ref) in convert.items():
            out += [
                "  UPDATE commissions SET is_test = true, reviewer_share_bps = 10000, gross_amount = 350.00,",
                "    platform_share = 0, honesty_fund_share = 0, csv_source = 'qa_sandbox',",
                f"    row_reference = '{orig_ref}', order_status = 'qa_sandbox', platform = NULL,",
                f"    updated_at = now() WHERE id = '{cid}' AND csv_source = '{SOURCE}';",
            ]
    out += [
        f"  DELETE FROM marketplace_remittances WHERE reference = '{REMIT_REF}';",
        f"  DELETE FROM moderation_logs WHERE log_id = '{LOG_ID}';",
        f"  IF EXISTS (SELECT 1 FROM commissions WHERE csv_source = '{SOURCE}') THEN",
        "    RAISE EXCEPTION 'demo rows remain after rollback';",
        "  END IF;",
        "END $$;",
    ]
    return "\n".join(out) + "\n"


